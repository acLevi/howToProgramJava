// Exercise 4.3: Write four different Java statements that add 1 to the integer variable x.

public class FourSumX {
    public static void main(String[] args) {
        int x = 0;

        x = x + 1;
        System.out.println(x);
        x += 1;
        System.out.println(x);
        x++;
        System.out.println(x);
        ++x;
        System.out.println(x);
    }
}
