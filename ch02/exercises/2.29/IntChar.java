// Exercise 2.29: Program that returns the integers values equivalent of determined chars.

public class IntChar {
    public static void main(String[] args) {
        System.out.println("Chars: A, B, C, a, b, c, 0, 1, 2, $, *, +, /, ' '.");
        System.out.printf("Int: %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d.", (int) 'A', (int) 'B', (int) 'C', (int) 'a', (int) 'b', (int) 'c', (int) '0', (int) '1', (int) '2', (int) '$', (int) '*', (int) '+', (int) '/', (int) 'A');
    }
}
